package io.gatediff.mapping;

import io.gatediff.openapi.OpenApiOperation;

import java.util.List;

/**
 * Generates ready-to-run, reviewable GateDiff YAML configuration files from confirmed operation mappings.
 */
public class YamlConfigGenerator {

    public static String generate(
            String projectName,
            String serviceId,
            String serviceName,
            String sourceBaseUrl,
            String targetBaseUrl,
            List<OperationMapping> mappings) {

        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by GateDiff CLI\n");
        sb.append("# Review paths and test payloads before executing migration tests.\n\n");
        sb.append("version: 1\n\n");

        sb.append("project:\n");
        sb.append("  name: ").append(escapeYaml(projectName)).append("\n");
        sb.append("  description: Gateway migration validation suite\n");
        sb.append("  environment: local\n\n");

        sb.append("defaults:\n");
        sb.append("  timeoutMs: 5000\n");
        sb.append("  retries: 1\n");
        sb.append("  compare:\n");
        sb.append("    status: true\n");
        sb.append("    jsonBody: true\n");
        sb.append("    additionalFields: true\n");
        sb.append("    ignoredJsonPaths:\n");
        sb.append("      - \"$.requestId\"\n");
        sb.append("      - \"$.timestamp\"\n");
        sb.append("    headers:\n");
        sb.append("      - \"content-type\"\n\n");

        sb.append("services:\n");
        sb.append("  - id: ").append(escapeYaml(serviceId)).append("\n");
        sb.append("    name: ").append(escapeYaml(serviceName)).append("\n");
        sb.append("    sourceBaseUrl: \"").append(sourceBaseUrl).append("\"\n");
        sb.append("    targetBaseUrl: \"").append(targetBaseUrl).append("\"\n");
        sb.append("    tests:\n");

        int testIdx = 1;
        for (OperationMapping m : mappings) {
            // Only generate tests for CONFIRMED or explicitly SUGGESTED mappings
            if (m.getStatus() == MappingStatus.UNRESOLVED) {
                continue;
            }

            OpenApiOperation op = m.getSourceOperation();
            String testId = "test-" + op.getMethod().toLowerCase() + "-" + sanitizeId(op.getPath());
            String samplePath = op.getPath().replace("{id}", "C-101").replace("{customerId}", "C-101");

            sb.append("      - id: ").append(testId).append("\n");
            sb.append("        name: \"").append(op.getMethod()).append(" ").append(op.getPath()).append("\"\n");
            sb.append("        method: ").append(op.getMethod()).append("\n");
            sb.append("        path: \"").append(samplePath).append("\"\n");
            sb.append("        expectedStatus: 200\n");

            if ("POST".equalsIgnoreCase(op.getMethod()) || "PUT".equalsIgnoreCase(op.getMethod()) || "PATCH".equalsIgnoreCase(op.getMethod())) {
                sb.append("        body: '{\"name\":\"Sample Customer\",\"tier\":\"STANDARD\"}'\n");
                sb.append("        headers:\n");
                sb.append("          Content-Type: application/json\n");
            }
            testIdx++;
        }

        return sb.toString();
    }

    private static String sanitizeId(String path) {
        return path.replaceAll("[^a-zA-Z0-9]+", "-").replaceAll("^-+|-+$", "").toLowerCase();
    }

    private static String escapeYaml(String s) {
        if (s == null) return "\"\"";
        return s.replace("\"", "\\\"");
    }
}
